-- Личность администраторов переустанавливается под точным сравнением (SEC-11-01, Task 11).
--
-- 004 сеет обоих администраторов через INSERT ... ON DUPLICATE KEY UPDATE role='admin' — под
-- коллацией, унаследованной от базы (utf8mb4_uca1400_ai_ci, регистро-/акцент-/пробело-
-- нечувствительной), которую заменяет на utf8mb4_nopad_bin только 005. Каждый файл миграции
-- применяется ровно один раз (migrate.go), поэтому 004 никогда не выполняется заново уже под
-- байт-точным сравнением.
--
-- Если на момент первого деплоя этой фичи в users уже существовала строка, чей id совпадает с
-- 'RoGogDBD' или 'irina2000aleshina' с точностью до регистра/акцента/концевого пробела — а
-- такую строку можно было создать анонимно через дореформенный
-- /api/v1/users/{userID}/settings (Decision 6 закрывает этот путь только для новых запросов,
-- не для строк, уже вставленных через него раньше) — 004 отдала role='admin' именно этой
-- чужой строке, а не строке настоящего администратора. После 005 сравнения стали точными, и
-- настоящий администратор при следующем входе получает не ту старую строку, а новую, с
-- role='user' по умолчанию (EnsureUser вставляет новую строку, не находит старую под другим
-- байтовым представлением). Итог — чужой аккаунт с правами администратора, оба настоящих
-- администратора без доступа и без пути восстановить его через API (нет ни одного маршрута,
-- меняющего role). Живьём воспроизведено на MariaDB 11.4: посеяна строка-коллизия, применены
-- 004→005 по реальным файлам, затем вход под настоящим логином — результат совпал с описанным
-- выше.
--
-- Эта миграция переустанавливает инвариант независимо от того, что оказалось в таблице к
-- моменту 004: UPDATE снимает role='admin' с любой строки, чей id не совпадает байт-в-байт ни
-- с одним из двух логинов (закрывает эскалацию — сравнение уже байт-точное, так как 006 идёт
-- строго после 005 по лексикографическому порядку имён файлов), INSERT/UPDATE гарантирует, что
-- обе настоящие строки — администраторы с доступом (восстанавливает легитимных админов). Оба
-- оператора идемпотентны, повторный прогон не меняет результат.
--
-- Данная миграция не отменяет саму возможность коллизии на будущее — её закрывает Decision 6
-- (владелец берётся из сессии, а не из URL, поэтому анонимная запись в users через API больше
-- недостижима) и Decision 19 (byte-точное сравнение при чтении). Эта миграция закрывает
-- конкретно то окно, где 004 успела отработать под старым сравнением.

-- has_access сбрасывается вместе с role, а не только role: пока строка ошибочно была
-- админом, доступ ей и так не нужен был (Decision 10 — админу достаточно самой role), но
-- именно поэтому владелец этой строки, будучи временно полноценным админом, мог сам себе
-- через POST /api/v1/admin/users/{login}/access выставить has_access=true — и без сброса
-- флага сохранил бы обычный доступ к приложению даже после того, как admin у него отобрали.
UPDATE users SET role = 'user', has_access = FALSE
 WHERE role = 'admin'
   AND id NOT IN ('RoGogDBD', 'irina2000aleshina');

INSERT INTO users (id, role, has_access) VALUES
  ('RoGogDBD', 'admin', TRUE),
  ('irina2000aleshina', 'admin', TRUE)
ON DUPLICATE KEY UPDATE role = 'admin', has_access = TRUE;
